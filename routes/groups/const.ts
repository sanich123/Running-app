import { LANGUAGES } from '@const/enums';
import { SPORTS_BTNS_VALUES } from '@const/sports';
import type { GroupCategoryTag, GroupSport } from '@R/services/groups/types';

export const GROUP_SPORTS: GroupSport[] = [
  SPORTS_BTNS_VALUES.run,
  SPORTS_BTNS_VALUES.walk,
  SPORTS_BTNS_VALUES.hike,
  SPORTS_BTNS_VALUES.bike,
];

export const GROUP_SPORT_LABELS: Record<GroupSport, { en: string; ru: string }> = {
  run: { en: 'Running', ru: 'Бег' },
  walk: { en: 'Walking', ru: 'Ходьба' },
  hike: { en: 'Hiking', ru: 'Пеший туризм' },
  bike: { en: 'Cycling', ru: 'Велоспорт' },
};

export function getGroupSportLabels(language: LANGUAGES): Record<GroupSport, string> {
  const locale = language === LANGUAGES.english ? 'en' : 'ru';
  return Object.fromEntries(GROUP_SPORTS.map((sport) => [sport, GROUP_SPORT_LABELS[sport][locale]])) as Record<
    GroupSport,
    string
  >;
}

