export function getGroupShareUrl(groupId: string) {
  const baseUrl = process.env.EXPO_PUBLIC_BASE_URL ?? '';
  const origin = baseUrl.includes('stage') ? 'https://stage-web.runich-app.ru' : 'https://runich-app.ru';
  return `${origin}/groups/${encodeURIComponent(groupId)}`;
}

